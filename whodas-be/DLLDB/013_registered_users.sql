-- =====================================================================
-- WHODAS 2.0 - Registrazione nuova utenza (user service)
-- ---------------------------------------------------------------------
-- Tabella delle utenze self-service registrate dagli utenti.
--
-- Ogni utenza e' collegata:
--   - al record LDAP creato durante la registrazione (ldap_uid = username)
--   - all'utente Keycloak risultante dal sync LDAP (keycloak_user_id)
--
-- Il codice fiscale, l'email e lo username sono unici (controlli 409
-- degli endpoint /api/v1/registration/check/cf e /check/email).
--
-- Stati ammessi:
--   ATTIVO       -> utenza attiva (stato iniziale)
--   SCADUTO      -> utenza scaduta
--   CANCELLATO   -> utenza cancellata (cancellazione logica)
-- =====================================================================

CREATE TABLE IF NOT EXISTS registered_users (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(100) NOT NULL UNIQUE,
    password_hash    VARCHAR(255) NOT NULL,
    first_name       VARCHAR(255) NOT NULL,
    last_name        VARCHAR(255) NOT NULL,
    birth_date       DATE,
    fiscal_code      VARCHAR(16)  NOT NULL UNIQUE,
    address          VARCHAR(255),
    postal_code      VARCHAR(10),
    comune           VARCHAR(100),
    city             VARCHAR(100),
    phone            VARCHAR(20),
    email            VARCHAR(255) NOT NULL UNIQUE,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ATTIVO',
    ldap_uid         VARCHAR(100) NOT NULL UNIQUE,
    keycloak_user_id VARCHAR(100),
    registered_at    TIMESTAMP    NOT NULL DEFAULT now(),
    modified_at      TIMESTAMP,
    password_temporary BOOLEAN NOT NULL DEFAULT FALSE
);

-- Vincolo di integrita': stato ammesso
ALTER TABLE registered_users
    DROP CONSTRAINT IF EXISTS ck_registered_users_status;
ALTER TABLE registered_users
    ADD CONSTRAINT ck_registered_users_status
    CHECK (status IN ('ATTIVO', 'SCADUTO', 'CANCELLATO'));

-- Indici per query frequenti
CREATE INDEX IF NOT EXISTS idx_registered_users_status ON registered_users (status);
