-- Crea la tabella dei tipi di compilazione (autosomministrato,
-- somministrato da intervistatore, proxy) e la collega alla tabella
-- assessments tramite chiave esterna.
-- =====================================================================

-- 1. Tabella dei tipi di compilazione
CREATE TABLE IF NOT EXISTS tab_type_compile_quest (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desc_type        VARCHAR(100) NOT NULL,
    specific_desc    TEXT,
    additional_notes TEXT
);

CREATE INDEX IF NOT EXISTS idx_tab_type_compile_quest_desc ON tab_type_compile_quest (desc_type);

-- 2. Colonna di riferimento nella tabella assessments
ALTER TABLE assessments
    ADD COLUMN IF NOT EXISTS compile_type_id BIGINT;

-- Vincolo FK: DROP + ADD rende lo script idempotente (stessa strategia di 008).
ALTER TABLE assessments
    DROP CONSTRAINT IF EXISTS fk_assessments_compile_type;
ALTER TABLE assessments
    ADD CONSTRAINT fk_assessments_compile_type
        FOREIGN KEY (compile_type_id) REFERENCES tab_type_compile_quest (id)
        ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_assessments_compile_type_id ON assessments (compile_type_id);

