CREATE TABLE IF NOT EXISTS questionnaire_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code VARCHAR(20) NOT NULL UNIQUE,
    domain VARCHAR(50) NOT NULL,
    domain_label VARCHAR(100),
    domain_label_it VARCHAR(100),
    question_text TEXT NOT NULL,
    question_text_it TEXT,
    icf_code VARCHAR(50),
    item_group VARCHAR(50),
    order_num INTEGER,
    response_type VARCHAR(20) DEFAULT 'LIKERT_5'
);

CREATE INDEX IF NOT EXISTS idx_questionnaire_items_domain ON questionnaire_items (domain);
CREATE INDEX IF NOT EXISTS idx_questionnaire_items_group ON questionnaire_items (item_group);
