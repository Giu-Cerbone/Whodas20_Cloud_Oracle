CREATE TABLE IF NOT EXISTS assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id VARCHAR(255) NOT NULL,
    version VARCHAR(20) DEFAULT '36-ITEM',
    status VARCHAR(20) DEFAULT 'DRAFT',
    mode VARCHAR(40) DEFAULT 'SELF_ADMINISTERED',
    language VARCHAR(10) DEFAULT 'it-IT',
    interviewer VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    completed_at TIMESTAMP,
    total_score DOUBLE PRECISION,
    overall_percent_disability DOUBLE PRECISION,
    overall_simple_score DOUBLE PRECISION,
    overall_complex_score DOUBLE PRECISION,
    overall_average_score DOUBLE PRECISION,
    total_items INTEGER,
    answered_items INTEGER,
    missing_items INTEGER,
    interpretation VARCHAR(50),
    scored_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_assessments_patient_id ON assessments (patient_id);
CREATE INDEX IF NOT EXISTS idx_assessments_status ON assessments (status);
