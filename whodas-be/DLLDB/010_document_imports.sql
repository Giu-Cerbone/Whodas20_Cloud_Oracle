-- =====================================================================
-- WHODAS 2.0 - Import documentale (document service)
-- ---------------------------------------------------------------------
-- Tre tabelle di proprietà del document service:
--   document_imports       traccia del file caricato (originale incluso)
--   document_import_fields  valori riconosciuti con confidenza e sorgente
--   document_import_items   risposte ai 36 item lette dal documento
--
-- Il document service non scrive mai sulle tabelle di patients,
-- assessments o item_responses: quei dati restano di proprietà dei
-- rispettivi servizi, che vengono chiamati via API REST. Queste tre
-- tabelle conservano solo la fotografia di cosa è stato letto dal
-- documento al momento dell'import.
-- =====================================================================

-- 1. traccia dell'import
CREATE TABLE IF NOT EXISTS document_imports (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name            VARCHAR(255) NOT NULL,
    file_type            VARCHAR(20),
    content_type         VARCHAR(100),
    file_size_bytes      BIGINT,
    file_checksum        VARCHAR(64),
    extraction_method    VARCHAR(20),
    -- IMPORTED      assessment creato e (se possible) calcolato
    -- ANALYZED_ONLY solo analisi del documento, nessun assessment creato
    status               VARCHAR(30) NOT NULL,
    compile_type_id      BIGINT,
    patient_id           VARCHAR(64),
    patient_name         VARCHAR(200),
    assessment_id        BIGINT,
    answers_imported     INTEGER,
    fields_extracted     INTEGER,
    extracted_text_length INTEGER,
    raw_text             TEXT,
    content              BYTEA,
    warnings             TEXT,
    created_at           TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_document_imports_patient_id ON document_imports (patient_id);
CREATE INDEX IF NOT EXISTS idx_document_imports_assessment_id ON document_imports (assessment_id);
CREATE INDEX IF NOT EXISTS idx_document_imports_status ON document_imports (status);
CREATE INDEX IF NOT EXISTS idx_document_imports_created_at ON document_imports (created_at DESC);

-- 2. valori riconosciuti nel documento
CREATE TABLE IF NOT EXISTS document_import_fields (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id         BIGINT NOT NULL,
    field_key         VARCHAR(100) NOT NULL,
    field_label       VARCHAR(200),
    raw_value         TEXT,
    normalized_value  TEXT,
    -- confidenza 0..1: sotto 0.6 il valore va verificato a mano
    confidence        DOUBLE PRECISION,
    -- ACROFORM (campi del modulo) | TABLE (tabella Word/Excel) | TEXT (testo libero)
    source            VARCHAR(20),
    created_at        TIMESTAMP NOT NULL,
    CONSTRAINT fk_document_import_fields_import
        FOREIGN KEY (import_id) REFERENCES document_imports (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_document_import_fields_import_id ON document_import_fields (import_id);
CREATE INDEX IF NOT EXISTS idx_document_import_fields_field_key ON document_import_fields (field_key);

-- 3. risposte agli item WHODAS 2.0 riconosciute
CREATE TABLE IF NOT EXISTS document_import_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id         BIGINT NOT NULL,
    -- codice del modello generato dal document service (D1S1..D1S36)
    item_code         VARCHAR(20) NOT NULL,
    domain            VARCHAR(40),
    domain_label_it   VARCHAR(100),
    question_text_it  VARCHAR(500),
    raw_value         VARCHAR(200),
    -- punteggio WHODAS 2.0 0..4, NULL se il documento non lo dichiarava
    score             INTEGER,
    confidence        DOUBLE PRECISION,
    source            VARCHAR(20),
    note              TEXT,
    days              INTEGER,
    created_at        TIMESTAMP NOT NULL,
    CONSTRAINT fk_document_import_items_import
        FOREIGN KEY (import_id) REFERENCES document_imports (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_document_import_items_score CHECK (score IS NULL OR (score >= 0 AND score <= 4)),
    CONSTRAINT ck_document_import_items_days CHECK (days IS NULL OR days >= 0),
    CONSTRAINT ck_document_import_items_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);

CREATE INDEX IF NOT EXISTS idx_document_import_items_import_id ON document_import_items (import_id);
CREATE INDEX IF NOT EXISTS idx_document_import_items_item_code ON document_import_items (item_code);
