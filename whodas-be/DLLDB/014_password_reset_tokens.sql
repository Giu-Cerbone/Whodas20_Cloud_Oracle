-- =====================================================================
-- WHODAS 2.0 - Password Reset Tokens (user service)
-- ---------------------------------------------------------------------
-- Tabella per la gestione dei token di reset password.
-- Ogni token:
--   - e' lungo 32 byte codificati in URL-safe Base64 (43-44 caratteri)
--   - scade dopo 24 ore (TOKEN_EXPIRY_HOURS)
--   - e' utilizzabile una sola volta (used = true dopo il reset)
--   - e' associato a username ed email dell'utente richiedente
-- =====================================================================

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token            VARCHAR(64)   NOT NULL UNIQUE,
    username         VARCHAR(100)  NOT NULL,
    email            VARCHAR(255)  NOT NULL,
    expiry_date      TIMESTAMP     NOT NULL,
    used             BOOLEAN       NOT NULL DEFAULT false,
    created_at       TIMESTAMP     NOT NULL DEFAULT now()
);

-- Indice per query di validazione token (username + non usato + non scaduto)
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_validation
    ON password_reset_tokens (username, used, expiry_date);

-- Indice per cleanup periodico dei token scaduti
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expiry
    ON password_reset_tokens (expiry_date);

-- Commento tabella
COMMENT ON TABLE password_reset_tokens IS 'Token per reset password self-service (scadenza 24h, single-use)';