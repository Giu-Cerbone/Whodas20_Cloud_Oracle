CREATE TABLE IF NOT EXISTS certificate_domain_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain VARCHAR(50),
    domain_label VARCHAR(100),
    domain_label_it VARCHAR(100),
    item_count INTEGER,
    raw_score INTEGER,
    average_score DOUBLE PRECISION,
    simple_score DOUBLE PRECISION,
    complex_score DOUBLE PRECISION,
    percent_disability DOUBLE PRECISION,
    certificate_id BIGINT NOT NULL,
    CONSTRAINT fk_certificate_domain_scores_certificate
        FOREIGN KEY (certificate_id) REFERENCES certificates (id)
);

CREATE INDEX IF NOT EXISTS idx_certificate_domain_scores_certificate_id ON certificate_domain_scores (certificate_id);
